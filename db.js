/**
 * =========================================================================
 * FAMILY MONEY - CAMADA DE BANCO DE DADOS HÍBRIDA (POSTGRESQL / LOCAL JSON)
 * =========================================================================
 * Se DATABASE_URL estiver configurada (ex: PostgreSQL no Coolify/Docker),
 * conecta-se automaticamente ao Postgres nativo.
 * Caso contrário, utiliza persistência local com o snapshot integral (seed)
 * garantindo que o sistema funcione 100% sem nenhuma dependência externa.
 */

const fs = require('fs');
const path = require('path');
const { Pool } = require('pg');

const DATABASE_URL = process.env.DATABASE_URL;
const SEED_FILE = path.join(__dirname, 'data', 'seed_backup.json');
const LOCAL_DB_FILE = path.join(__dirname, 'data', 'local_db.json');

let pool = null;
let isPostgres = false;
let localDb = null;
let dbVersion = Date.now();

/**
 * Retorna a versão atômica atual da base de dados
 */
function getDbVersion() {
  return dbVersion;
}

/**
 * Incrementa a versão atômica do banco notificando mutações
 */
function bumpDbVersion() {
  dbVersion = Date.now();
  return dbVersion;
}

// Tabelas gerenciadas pelo sistema
const MANAGED_TABLES = [
  'accounts',
  'cards',
  'categories',
  'tags',
  'fixed_items',
  'transactions',
  'paid_card_bills',
  'app_users',
  'app_backups'
];

/**
 * Carrega a base local a partir de local_db.json ou seed_backup.json
 */
function loadLocalDatabase() {
  if (fs.existsSync(LOCAL_DB_FILE)) {
    try {
      const content = fs.readFileSync(LOCAL_DB_FILE, 'utf-8');
      localDb = JSON.parse(content);
      
      let dirty = false;
      // Podar backups históricos para manter tamanho < 3MB
      if (localDb.app_backups && localDb.app_backups.length > 5) {
        localDb.app_backups.sort((a, b) => new Date(b.created_at || 0) - new Date(a.created_at || 0));
        localDb.app_backups = localDb.app_backups.slice(0, 5);
        dirty = true;
      }
      // Deduplicar app_users por email
      if (localDb.app_users && localDb.app_users.length > 3) {
        const uniqueUsers = [];
        const seen = new Set();
        for (const u of localDb.app_users) {
          const email = (u.email || '').toLowerCase().trim();
          if (!seen.has(email)) {
            seen.add(email);
            uniqueUsers.push(u);
          }
        }
        localDb.app_users = uniqueUsers;
        dirty = true;
      }

      if (dirty) {
        saveLocalDatabase();
      }
      return;
    } catch (e) {
      console.warn('Erro ao ler local_db.json, regerando do seed:', e.message);
    }
  }

  // Fallback para o seed_backup.json auditado
  if (fs.existsSync(SEED_FILE)) {
    const seed = JSON.parse(fs.readFileSync(SEED_FILE, 'utf-8'));
    localDb = {};
    for (const tbl of MANAGED_TABLES) {
      let records = seed.tables[tbl]?.records || [];
      if (tbl === 'app_backups' && records.length > 5) {
        records = records.slice(0, 5);
      }
      localDb[tbl] = records;
    }
    saveLocalDatabase();
  } else {
    localDb = {};
    for (const tbl of MANAGED_TABLES) {
      localDb[tbl] = [];
    }
  }
}

function saveLocalDatabase() {
  try {
    const dir = path.dirname(LOCAL_DB_FILE);
    if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(LOCAL_DB_FILE, JSON.stringify(localDb, null, 2), 'utf-8');
  } catch (err) {
    console.error('Erro ao salvar local_db.json:', err.message);
  }
}

/**
 * Inicializa conexão com PostgreSQL ou carrega o banco local
 */
async function initDb() {
  if (DATABASE_URL) {
    console.log('[DB] Conectando ao PostgreSQL via DATABASE_URL...');
    try {
      pool = new Pool({
        connectionString: DATABASE_URL,
        ssl: DATABASE_URL.includes('sslmode=require') ? { rejectUnauthorized: false } : false
      });
      const client = await pool.connect();
      console.log('[DB] Conexão com PostgreSQL estabelecida com sucesso!');
      client.release();
      isPostgres = true;

      // Executar schema se necessário
      await initPostgresSchema();
      // Executar carga inicial se a tabela transactions estiver vazia
      await seedPostgresIfEmpty();
      return;
    } catch (err) {
      console.error('[DB] Falha ao conectar no PostgreSQL:', err.message);
      console.log('[DB] Ativando contingência de banco local com dados completos.');
    }
  }

  console.log('[DB] Operando com motor de persistência local.');
  loadLocalDatabase();
}

